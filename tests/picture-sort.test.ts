import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { startPictureSort } from "../components/upload/picture-sort";

const pointer = (type: string, x: number, y: number, id = 1) => {
  const event = new MouseEvent(type, {
    bubbles: true,
    cancelable: true,
    clientX: x,
    clientY: y,
    button: 0,
  });
  Object.defineProperty(event, "pointerId", { value: id });
  return event as PointerEvent;
};

describe("picture sorting", () => {
  let cleanup: (() => void) | undefined;
  beforeEach(() => vi.useFakeTimers());
  afterEach(() => {
    cleanup?.();
    document.body.innerHTML = "";
    vi.useRealTimers();
  });
  const setup = () => {
    const list = document.createElement("div");
    document.body.append(list);
    const cards = Array.from({ length: 3 }, (_, i) => {
      const card = document.createElement("div");
      card.className = "k-upload-file-picture-item";
      const left = i === 1 ? 104 : 0;
      const top = i === 2 ? 104 : 0;
      card.getBoundingClientRect = () =>
        ({ left, top, right: left + 96, bottom: top + 96, width: 96, height: 96 }) as DOMRect;
      Object.defineProperties(card, { offsetLeft: { value: left }, offsetTop: { value: top } });
      list.append(card);
      return card;
    });
    list.getBoundingClientRect = () => ({ left: 0, top: 0, right: 200, bottom: 200 }) as DOMRect;
    const sort = vi.fn();
    cleanup = startPictureSort(pointer("pointerdown", 40, 40), cards[0], sort);
    return { list, cards, sort };
  };
  it("moves the whole card immediately, previews wrapped slots and commits after settling", () => {
    const { list, cards, sort } = setup();
    document.dispatchEvent(pointer("pointermove", 40, 145));
    expect(cards[0].classList.contains("k-upload-sort-dragging")).toBe(true);
    expect(cards[0].style.transform).toBe("translate3d(0px, 105px, 0)");
    expect(cards[1].style.transform).toBe("translate3d(-104px, 0px, 0)");
    expect(cards[2].style.transform).toBe("translate3d(104px, -104px, 0)");
    expect(list.querySelector<HTMLElement>(".k-upload-sort-placeholder")?.style.top).toBe("104px");
    expect(sort).not.toHaveBeenCalled();
    document.dispatchEvent(pointer("pointerup", 40, 145));
    expect(sort).not.toHaveBeenCalled();
    vi.advanceTimersByTime(180);
    expect(sort).toHaveBeenCalledExactlyOnceWith(0, 2);
    expect(cards[0].getAttribute("style")).toBeNull();
    expect(list.querySelector(".k-upload-sort-placeholder")).toBeNull();
  });
  it.each(["escape", "pointercancel", "outside"])("restores original order on %s", (reason) => {
    const { cards, sort } = setup();
    document.dispatchEvent(pointer("pointermove", 140, 40));
    if (reason === "escape")
      document.dispatchEvent(new KeyboardEvent("keydown", { key: "Escape" }));
    else
      document.dispatchEvent(
        pointer(reason === "outside" ? "pointerup" : "pointercancel", 400, 400),
      );
    vi.runAllTimers();
    expect(sort).not.toHaveBeenCalled();
    expect(cards.every((card) => !card.style.transform)).toBe(true);
  });
  it("preserves clicks below the movement threshold and ignores other pointers", () => {
    const { cards, sort } = setup();
    document.dispatchEvent(pointer("pointermove", 140, 40, 2));
    document.dispatchEvent(pointer("pointermove", 42, 40));
    document.dispatchEvent(pointer("pointerup", 42, 40));
    const click = new MouseEvent("click", { bubbles: true, cancelable: true });
    expect(cards[0].dispatchEvent(click)).toBe(true);
    expect(sort).not.toHaveBeenCalled();
  });
  it("suppresses the click generated by dropping a card, then restores clicks", () => {
    const { cards } = setup();
    document.dispatchEvent(pointer("pointermove", 140, 40));
    document.dispatchEvent(pointer("pointerup", 140, 40));
    expect(
      cards[0].dispatchEvent(new MouseEvent("click", { bubbles: true, cancelable: true })),
    ).toBe(false);
    vi.runAllTimers();
    expect(
      cards[0].dispatchEvent(new MouseEvent("click", { bubbles: true, cancelable: true })),
    ).toBe(true);
  });
  it("cleans up on unmount without committing", () => {
    const { list, cards, sort } = setup();
    document.dispatchEvent(pointer("pointermove", 140, 40));
    cleanup?.();
    document.dispatchEvent(pointer("pointerup", 140, 40));
    vi.runAllTimers();
    expect(sort).not.toHaveBeenCalled();
    expect(list.querySelector(".k-upload-sort-placeholder")).toBeNull();
    expect(cards[0].style.transform).toBe("");
  });
});
